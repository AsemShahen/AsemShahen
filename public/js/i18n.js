const I18N = Vue.reactive({ lang: 'ar', en: EN_DICT });

function t(str, vars) {
  if (str === null || str === undefined) return str;
  if (typeof str !== 'string') return str;
  const lang = I18N.lang;
  let s = lang === 'en' && EN_DICT[str] !== undefined ? EN_DICT[str] : str;
  if (vars && typeof s === 'string') {
    for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k]));
  }
  return s;
}

function applyLang() {
  const l = I18N.lang;
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr';
  document.title = t('نظام المحاسب');
}

function setLang(l) {
  if (l !== 'ar' && l !== 'en') l = 'ar';
  I18N.lang = l;
  localStorage.setItem('app_lang', l);
  applyLang();
}

function currentLang() { return I18N.lang; }
function langLabel(l) { return l === 'en' ? 'English' : 'العربية'; }

Vue.watch(() => I18N.lang, (v) => {
  localStorage.setItem('app_lang', v);
  applyLang();
});

(function initLang() {
  const saved = localStorage.getItem('app_lang');
  I18N.lang = saved === 'en' ? 'en' : 'ar';
  applyLang();
})();
